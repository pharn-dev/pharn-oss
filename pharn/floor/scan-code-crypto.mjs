#!/usr/bin/env node
// pharn/floor/scan-code-crypto.mjs — deterministic WEAK-CRYPTO-PRIMITIVE scanner over a CODE file (CONSTITUTION P0/P5).
//
// The crypto twin of pharn/floor/scan-code-secrets.mjs / scan-code-injection.mjs. Where those scanners back
// the `secrets-in-code` / `injection` LENSes' FLOOR sub-checks, this one backs the `insecure-crypto` LENS's
// FLOOR sub-check (pharn-review/insecure-crypto/): does a line NAME a known-weak crypto primitive — a broken
// hash (MD5 / SHA-1) in a hashing API, a broken cipher (DES/3DES/RC4, or Node's deprecated no-IV createCipher)
// in a cipher constructor, ECB block-cipher mode, a non-crypto RNG (Math.random) used for security material,
// or a hardcoded IV/salt/nonce literal?
// Detection is a FIXED REGEX SET over the file's lines — non-LLM, no judgment. It reduces to ARCHITECTURE §2
// primitive #3 (regex / enum check).
//
// HONEST BOUND (the trust-fence / secrets-in-code precedent, P0): this detects a weak-primitive PATTERN's
// PRESENCE + line. It does NOT decide the usage is actually a vulnerability (MD5 for a password vs a
// non-security cache key; SHA-1 for password hashing vs a git blob id), does NOT know the operand's real
// provenance, and does NOT judge whether the code is "cryptographically correct / secure". "Detected a
// weak-crypto primitive on line N" is a real guarantee; "the crypto is correct / the code is secure" is NOT.
// Novel/aliased algorithm references, split literals, or a weak primitive from an unlisted library evade a
// fixed regex set. Full crypto correctness is ADVISORY judgment the LENS surfaces — NOT this floor.
//
// INJECTION-IMMUNE BY CONSTRUCTION (P2): the verdict is regex membership over the TEXT only. A code comment
// that CLAIMS "approved / secure / do not flag / mark clean" cannot suppress a real hit; a comment that
// CLAIMS "weak crypto here" cannot manufacture one. No free text moves the verdict — the strongest form of
// the trust-fence discipline. (See the ★ tests in scan-code-crypto.test.mjs — they are the whole reason this
// is FLOOR, not judgment.)
//
// The two context-scoped patterns (insecure-random, hardcoded-iv-salt) are deliberately high-signal: a BARE
// Math.random() (a non-security shuffle) and a FRESHLY GENERATED iv (crypto.randomBytes) are true-negatives
// — the "is this bare RNG / this IV actually crypto-sensitive?" call is Layer-2 LENS judgment, never this
// floor. This mirrors the secrets scanner's `assigned-secret-literal` context-scoping.
//
// Per-file by contract: every verdict is about ONE file's text, mirroring scan-code-secrets.mjs. The scanner
// takes one `<code-file>`, or many through `--files` (review-fanout) — the batch mode `/pharn-review`'s
// prefilter spawns once per review — and each file's verdict is the same either way
// (pharn/floor/code-scanner-cli.mjs owns both modes). A cross-file / directory sweep is a FUTURE increment.
//
// Non-LLM, stdlib-only, fail-closed. MIRRORS the fail-closed contract of pharn/floor/scan-code-secrets.mjs:
// a missing / non-file target is an ERROR (nonzero exit, NOTHING on stdout), never a silent "clean".
//
// Usage:  node pharn/floor/scan-code-crypto.mjs <code-file>
//         node pharn/floor/scan-code-crypto.mjs --files <nul-separated-list | ->
// Output: {"found":<bool>,"hits":[{"line":<int>,"kind":"<pattern-kind>"},...]} on stdout; exit 0 on a
//         successful scan (whatever the result). `found` === (hits.length > 0); hits sorted by line, then kind.
//         Exits non-zero (writing NOTHING to stdout) if the target is missing / not a regular file (P5).
//         With --files: one {"results":[…]} document, one entry per listed path (code-scanner-cli.mjs).

import "./runtime-floor.mjs";
import { runScannerCli } from "./code-scanner-cli.mjs";

// Security-material name set for the context-scoped insecure-random pattern (membership, P5). A bare
// Math.random() with none of these words on the line is NOT flagged (that is Layer-2 judgment).
//
// Each word matches as an identifier SEGMENT, never as an unanchored substring — and that anchoring is
// QUANTIFIED OVER THE WHOLE SET. The enumeration below IS the deliverable, because the defect it repairs
// was a rule written for one member of a set: through 2.7.10 only `iv` was boundary-anchored, so the other
// ten fired inside ordinary identifiers and `keys[Math.floor(Math.random() * keys.length)]` plus a
// Fisher-Yates shuffle over `monkeys` — two of the commonest Math.random uses in real code — both flagged.
// A heuristic that floods on idiomatic code erodes the lens it backs.
//
// Four branches per word, generated by segment(), so a word added to SECMAT_WORDS later inherits all four
// for free rather than needing its own hand-written anchor (which is how `iv` came to be the only one):
//   1. bare lowercase head, NO plural — `key`, `key_material`, `keyMaterial`; blocks `keys`, `monkeys`,
//      `Object.keys`, `salted`, and `iv` inside `private` / `receive` / `derive`.
//   2. camelCase segment, plural OK   — `sessionToken`, `apiKeys`; the uppercase initial IS the boundary.
//   3. ALL-CAPS segment, plural OK    — `API_KEY`, `API_KEYS`; blocks `MONKEYS`, and `IV` inside `PRIVATE`.
//   4. snake/kebab tail, plural OK    — `api_keys`, `api-key`.
// The plural `s` is admitted on a CONTINUATION segment (2-4) and never on a bare lowercase word (1). That
// asymmetry is the whole separation between `apiKeys` (kept) and `keys` (dropped): both end in `keys`, and
// nothing but the left context distinguishes a compound whose head names security material from a plural
// English noun.
//
// THE CHANGE IS NOT MONOTONE, and both directions are named — because a rewrite that folds a per-member
// EXCEPTION into a uniform rule moves that member toward the rule from whichever side it was on, and a
// hand-written one-word exception is usually STRICTER than the rule it is being folded into. So the
// member carrying its own anchor is exactly where a "tightening" WIDENS. Diffed by running the old and
// new patterns over the same lines, not reasoned about:
//
//   NARROWED (matched before, does not now):
//     • a bare lowercase plural — `keys`, `secrets`, `tokens`. This is the false positive being removed,
//       and it is indistinguishable from `Object.keys` by boundary alone.
//     • a word glued inside a longer lowercase word — `mytoken`, `salted`.
//     • a MIXED-case spelling — `tOKEN`, `KeY`. Deliberate: the old `i` flag case-folded the whole
//       pattern, and branches 2-4 must READ case to tell `apiKeys` from `keys`. Only the Math.random
//       conjunct keeps its case-insensitivity (see ci() below); the SECMAT half gave it up on purpose.
//   WIDENED (did not match before, does now):
//     • `iv` as a camelCase or ALL-CAPS segment — `myIv`, `sessionIv`. The old branch was
//       `(?<![a-z])iv(?![a-z])` under the `i` flag, where `[a-z]` case-folds, so ANY preceding letter
//       blocked it and `myIv` was a miss. Branch 2 now admits it, which is the symmetric half of giving
//       every word the same treatment: `iv` gains the camelCase reach the other ten always had.
//       `myIv = Math.random()` is precisely what this kind exists to catch, so the widening is the point.
//
// COST, re-derived for THIS form (6.58.1), never inherited from the form it replaced. The pattern is
// `^(?=.*RNG)(?=.*SECMAT)` under the `m` flag. Through 6.58.0 it had no `^`, and `(?=.*X)` re-scanned from
// EVERY start index, so a line with no hit cost O(n²): 40 KB of `a.b.b.b…` took ~1 s, and every 200 KB
// fixture of the 2026-10-12 review was killed at 20 s (TST-1). With the anchor the lookaheads run
// only where multiline `^` holds, at index 0 and right after a line terminator. Each run between
// terminators is scanned once per lookahead, so a line costs O(n). It still has no exponential path:
// the branches are literal-prefixed and disjoint, each carries at most one `s?`, and no quantifier nests
// over an ambiguous alternation. The 2026-08-20 figures (the 4x branch growth cost ~1.2x, 203.9 ms ->
// 251.2 ms at 20 KB) measured the superseded unanchored form and say nothing about this one.
// SAME LINES MATCH, and why: `.` excludes exactly the four line terminators (\n, \r, U+2028, U+2029),
// and multiline `^` holds exactly at index 0 and after one of those four. So the old form succeeded at
// a start `i` iff it succeeds at the start of i's terminator-free run. A start ON a terminator never
// succeeded, because both conjuncts begin with a letter. The lookbehinds and `\b` read the whole string,
// whatever the start. A bare `^` WITHOUT `m` is not equivalent: it would drop a hit after a lone `\r` or a
// U+2028 inside one split line. What IS pinned is a MEMBERSHIP test (completed vs. killed under a
// subprocess timeout, the ★ ReDoS test), never a stopwatch compared to a threshold. The timeout is also
// what keeps a red TERMINATING rather than hanging.
//
// DELIBERATE DIVERGENCE, stated so a later reader does not read it as drift: `hardcoded-iv-salt` below
// keeps its own `\b(?:iv|salt|nonce)\b` anchoring and does NOT use this matcher. It matches an ASSIGNMENT
// TARGET rather than any mention on the line, so its boundary question is a different one, and no reported
// failure bears on it — a separate axis of change (P3/P7).
const SECMAT_WORDS = ["token", "secret", "password", "passphrase", "credential", "session", "nonce", "otp", "salt", "key", "iv"];

/** One word -> its 4-branch identifier-SEGMENT matcher (the enumeration described above). */
function segment(w) {
  const lo = w;
  const Ti = w[0].toUpperCase() + w.slice(1);
  const UP = w.toUpperCase();
  return [
    `(?<![A-Za-z0-9])${lo}(?![a-z0-9])`, // 1. bare lowercase head, no plural
    `${Ti}s?(?![a-z0-9])`, // 2. camelCase segment (its capital IS the left boundary)
    `(?<![A-Za-z0-9])${UP}S?(?![A-Za-z0-9])`, // 3. ALL-CAPS segment
    `(?<=[_-])${lo}s?(?![a-z0-9])`, // 4. snake / kebab tail
  ].join("|");
}
const SECMAT = `(?:${SECMAT_WORDS.map(segment).join("|")})`;

// Branches 2-4 discriminate on CASE, so the insecure-random RegExp below cannot carry the `i` flag any
// more. That drop has TWO consequences and only one of them is compensated. (1) The Math.random conjunct
// must keep its case-insensitivity EXPLICITLY, or dropping the flag would silently narrow a half of the
// pattern this increment never meant to touch: ci() expands that literal to per-character classes, which
// is precisely what `i` did for it before, so THAT half is unchanged. (2) The SECMAT half genuinely does
// lose case-folding, and that is intended, not an oversight — a mixed-case `tOKEN` no longer matches,
// which is the price of being able to tell `apiKeys` from `keys` at all. Both are listed in the
// not-monotone block above.
const ci = (s) => s.replace(/[A-Za-z]/g, (c) => `[${c.toLowerCase()}${c.toUpperCase()}]`);

// The fixed detection set — six weak-crypto primitives biased to well-known, high-signal API/name shapes.
// Each is a MEMBERSHIP test over the text (P5), anchored to an API call / algorithm token / assignment so it
// does NOT fire on a weak-looking substring inside an unrelated identifier ("nodes", "describe", "salted").
// Adding or removing a pattern is the ONLY axis of change here (P3).
//
// NOTE (accepted duplication, deferred P7): these detectors are the crypto siblings of scan-code-secrets.mjs
// / scan-code-injection.mjs; they detect DIFFERENT things. Consolidating any shared regex fragment would
// touch a separate axis (those scanners + their lenses) — deferred, not done speculatively here.
const PATTERNS = [
  // Broken hash primitives NAMED in a hashing API (Node createHash, Python hashlib, Java MessageDigest).
  { kind: "weak-hash-md5", re: /\bcreateHash\(\s*["']md5["']|\bhashlib\.md5\s*\(|\bMessageDigest\.getInstance\(\s*["']MD5["']/i },
  { kind: "weak-hash-sha1", re: /\bcreateHash\(\s*["']sha-?1["']|\bhashlib\.sha1\s*\(|\bMessageDigest\.getInstance\(\s*["']SHA-?1["']/i },
  // Broken/deprecated block ciphers (DES / 3DES / DESede) NAMED in a cipher constructor / getInstance.
  {
    kind: "weak-cipher-des",
    re: /\bcreate(?:Cipher|Decipher)(?:iv)?\(\s*["'](?:3?des|desede)\b|\.getInstance\(\s*["'](?:3?des|desede)\b/i,
  },
  // Broken STREAM cipher RC4 NAMED in a cipher constructor / getInstance (createCipheriv("rc4", …), getInstance("RC4")).
  { kind: "weak-cipher-rc4", re: /\bcreate(?:Cipher|Decipher)(?:iv)?\(\s*["']rc4\b|\.getInstance\(\s*["']rc4\b/i },
  // Node's DEPRECATED no-IV crypto.createCipher(/createDecipher( — derives key+IV insecurely (weak KDF, zero IV).
  // Anchored so the SAFE createCipheriv(/createDecipheriv( does NOT match: the `iv` between `Cipher` and `(`
  // blocks `Cipher\(`. Flags the API misuse regardless of the algorithm string.
  { kind: "deprecated-createcipher", re: /\bcreate(?:Cipher|Decipher)\(/ },
  // ECB block-cipher mode (semantically insecure regardless of cipher): `aes-256-ecb`, `.../ECB/...`, MODE_ECB.
  // Linear as written: `\b` holds only at a word's edges, so `[a-z0-9]+` starts at most once per word. Timed
  // alone on 2026-10-13, 800 KB alnum runs took a few ms; the ★ ReDoS test pins a long run before `-ecb`.
  { kind: "ecb-mode", re: /\b[a-z0-9]+-ecb\b|["'][A-Za-z0-9]+\/ECB\//i },
  // Non-crypto RNG used for SECURITY MATERIAL: Math.random() on a line ALSO naming a token/secret/key/etc
  // as an identifier SEGMENT (see SECMAT above). No `i` flag — the segment branches read case. The
  // leading `^` keeps it linear in line length; the `m` flag keeps it matching the same lines (see COST
  // above). Without `^` the lookaheads run from every index again; without `m` a hit after a lone `\r` or
  // a U+2028 is lost.
  { kind: "insecure-random", re: new RegExp(`^(?=.*\\b${ci("Math")}\\.${ci("random")}\\s*\\()(?=.*${SECMAT})`, "m") },
  // Hardcoded IV / salt / nonce: an iv|salt|nonce-named field assigned a LITERAL (quoted string, a
  // Buffer.from("...") over a quoted literal, a new Uint8Array([...]) byte array, or a `[0x..]` array) —
  // rather than a freshly generated value (crypto.randomBytes(...) is a TRUE-NEGATIVE, not flagged).
  {
    kind: "hardcoded-iv-salt",
    re: /\b(?:iv|salt|nonce)\b\s*[:=]\s*(?:["'][^"']*["']|Buffer\.from\(\s*["']|new\s+Uint8Array\(\s*\[|\[\s*(?:0x)?\d)/i,
  },
];

/** The hits for one file's text. Keeps nothing between calls: no PATTERNS regex carries a `g`/`y` flag. */
export function scanText(text) {
  const hits = [];
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    for (const { kind, re } of PATTERNS) {
      if (re.test(lines[i])) hits.push({ line: i + 1, kind });
    }
  }
  // Deterministic order: by line, then by kind (a line matching >1 pattern yields >1 hit, stably ordered).
  hits.sort((a, b) => a.line - b.line || a.kind.localeCompare(b.kind));
  return hits;
}

if (import.meta.main) process.exitCode = runScannerCli("scan-code-crypto", scanText, process.argv.slice(2));
