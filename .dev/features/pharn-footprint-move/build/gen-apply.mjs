// gen-apply.mjs — render apply.py + HUMAN-PATCH.md for the 10 hook-protected files from (BEFORE = the worktree's
// committed HEAD, AFTER = the scratch copy). Edits are `git diff` hunks, each widened with more context until its
// old text occurs exactly once in the file it applies to (applied in order, each against the text so far).
//
//   node gen-apply.mjs <worktree> <scratch-copy> <out-dir>
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const [WT, WC, OUT] = process.argv.slice(2);
const FILES = [
  [".claude/hooks/protect-trusted-paths.cjs"],
  [".claude/hooks/enforce-writes-scope.cjs"],
  [".claude/hooks/set-writes-scope.cjs"],
  [".claude/hooks/require-loop-record.cjs"],
  [".claude/settings.json"],
  [".github/CODEOWNERS"],
  ["pharn/CONSTITUTION.md"],
  ["pharn/ARCHITECTURE.md"],
  ["THREAT-MODEL.md", "pharn/THREAT-MODEL.md"],
  ["LIMITS.md", "pharn/LIMITS.md"],
];
const sha = (s) => createHash("sha256").update(s, "utf8").digest("hex");
const count = (hay, needle) => hay.split(needle).length - 1;

function hunks(before, after) {
  const dir = fs.mkdtempSync(path.join(OUT, ".gen-"));
  const a = path.join(dir, "a"), b = path.join(dir, "b");
  fs.writeFileSync(a, before);
  fs.writeFileSync(b, after);
  let out = "";
  try {
    execFileSync("git", ["diff", "--no-index", "--no-color", "-U0", a, b], { encoding: "utf8" });
  } catch (e) {
    out = e.stdout; // exit 1 = differences
  }
  fs.rmSync(dir, { recursive: true, force: true });
  const res = [];
  for (const m of out.matchAll(/^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/gm)) {
    res.push({ oStart: +m[1], oLen: m[2] === undefined ? 1 : +m[2], nStart: +m[3], nLen: m[4] === undefined ? 1 : +m[4] });
  }
  return res;
}

function edits(before, after) {
  const bl = before.split("\n"), al = after.split("\n");
  const hs = hunks(before, after);
  // Convert each hunk to a (old lines, new lines) pair with symmetric context, widened until unique in `before`.
  const raw = hs.map((h) => {
    const o0 = h.oLen === 0 ? h.oStart : h.oStart - 1; // 0-based index of first old line (pure insert: insert AFTER oStart)
    const n0 = h.nLen === 0 ? h.nStart : h.nStart - 1;
    return { o0, oLen: h.oLen, n0, nLen: h.nLen };
  });
  const out = [];
  let text = before;
  // offset between old and new numbering is consistent because context is taken from the OLD side only
  let prevEnd = 0; // backward context never reaches into a region an earlier edit already rewrote
  for (const r of raw) {
    let ctx = 1;
    for (;;) {
      const s = Math.max(prevEnd, r.o0 - ctx), e = Math.min(bl.length, r.o0 + r.oLen + ctx);
      const oldText = bl.slice(s, e).join("\n");
      const pre = bl.slice(s, r.o0), post = bl.slice(r.o0 + r.oLen, e);
      const newText = [...pre, ...al.slice(r.n0, r.n0 + r.nLen), ...post].join("\n");
      if (oldText.length > 0 && count(text, oldText) === 1) {
        out.push({ old: oldText, new: newText, line: r.o0 + 1 });
        text = text.replace(oldText, () => newText);
        prevEnd = r.o0 + r.oLen;
        break;
      }
      ctx++;
      if (ctx > 60) throw new Error(`cannot make a hunk unique near line ${r.o0 + 1}`);
    }
  }
  if (text !== after) throw new Error("replaying the edits does not reproduce AFTER");
  return out;
}

const data = [];
for (const [from, to] of FILES) {
  const before = execFileSync("git", ["-C", WT, "show", `HEAD:${from}`], { encoding: "utf8" });
  const after = fs.readFileSync(path.join(WC, to || from), "utf8");
  const e = edits(before, after);
  data.push({ path: from, new_path: to || null, before_sha: sha(before), after_sha: sha(after), edits: e });
}

const py = `#!/usr/bin/env python3
"""apply.py -- pharn-footprint-move (SKILLS 7.0.0): the human patch for the 10 hook-protected files.

GENERATED by an agent-side script from the reviewed scratch copy; HUMAN-PATCH.md is its readable twin.
The agent may not write these files through any tool (CLAUDE.md hard constraint 1), so the maintainer runs this.

  python3 .dev/features/pharn-footprint-move/apply.py --dry-run   # check only, write nothing
  python3 .dev/features/pharn-footprint-move/apply.py             # apply

It refuses, writing NOTHING, unless every target's sha256 equals its pinned BEFORE hash, every edit's old text
occurs exactly once in the text it applies to, every result's sha256 equals its pinned AFTER hash, and no
rename target exists yet. Two renames: THREAT-MODEL.md -> pharn/THREAT-MODEL.md, LIMITS.md -> pharn/LIMITS.md
(each written with its edits, then the root copy removed). On success it prints one line per file and deletes
itself. Do not commit: hand back to the agent (L68).
Stdlib only.
"""
import hashlib, json, os, sys

DATA = json.loads(${JSON.stringify(JSON.stringify(data))})

def sha(b):
    return hashlib.sha256(b).hexdigest()

def main():
    dry = "--dry-run" in sys.argv[1:]
    extra = [a for a in sys.argv[1:] if a != "--dry-run"]
    if extra:
        sys.exit("usage: apply.py [--dry-run]")
    root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    plan = []
    for f in DATA:
        src = os.path.join(root, f["path"])
        try:
            with open(src, "rb") as fh:
                raw = fh.read()
        except OSError as e:
            sys.exit(f"REFUSED, nothing written: cannot read {f['path']}: {e}")
        if sha(raw) != f["before_sha"]:
            sys.exit(f"REFUSED, nothing written: {f['path']} is not the pinned BEFORE ({f['before_sha'][:12]}...)")
        text = raw.decode("utf-8")
        for i, e in enumerate(f["edits"]):
            n = text.count(e["old"])
            if n != 1:
                sys.exit(f"REFUSED, nothing written: {f['path']} edit {i + 1}: old text occurs {n} times")
            text = text.replace(e["old"], e["new"], 1)
        out = text.encode("utf-8")
        if sha(out) != f["after_sha"]:
            sys.exit(f"REFUSED, nothing written: {f['path']} result is not the pinned AFTER ({f['after_sha'][:12]}...)")
        dest = os.path.join(root, f["new_path"] or f["path"])
        if f["new_path"] and os.path.lexists(dest):
            sys.exit(f"REFUSED, nothing written: rename target {f['new_path']} already exists")
        plan.append((f, src, dest, out))
    if dry:
        for f, _, _, _ in plan:
            arrow = f" -> {f['new_path']}" if f["new_path"] else ""
            print(f"would apply {len(f['edits'])} edit(s): {f['path']}{arrow}")
        print("DRY RUN: every pin matches; nothing written.")
        return
    for f, src, dest, out in plan:
        with open(dest, "wb") as fh:
            fh.write(out)
        if f["new_path"]:
            os.remove(src)
        arrow = f" -> {f['new_path']}" if f["new_path"] else ""
        print(f"applied {len(f['edits'])} edit(s): {f['path']}{arrow}  sha256 {f['after_sha'][:12]}")
    os.remove(os.path.abspath(__file__))
    print("APPLIED. apply.py deleted itself. Do not commit: hand back to the agent.")

if __name__ == "__main__":
    main()
`;
fs.writeFileSync(path.join(OUT, "apply.py"), py);

// ── HUMAN-PATCH.md ──
const fence = (s) => {
  let f = "```";
  while (s.includes(f)) f += "`";
  return f;
};
let md = `# HUMAN-PATCH — pharn-footprint-move

<!-- GENERATED from apply.py's data by an agent-side render script; edit the source and re-render, never this file. -->

The readable twin of \`apply.py\`: every edit it makes to the ten hook-protected files. The agent may not write
these files through any tool (CLAUDE.md hard constraint 1), so the maintainer applies them by running the script.
This file is for reading; the script's bytes are what count.

## How to apply

1. In this worktree, at the commit the agent hands over, check first (writes nothing):

   \`\`\`bash
   python3 .dev/features/pharn-footprint-move/apply.py --dry-run
   \`\`\`

   then apply:

   \`\`\`bash
   python3 .dev/features/pharn-footprint-move/apply.py
   \`\`\`

2. It refuses, writing nothing, unless every target matches its pinned BEFORE hash, every edit's old text occurs
   exactly once, every result matches its pinned AFTER hash, and neither rename target exists. On success it prints
   one line per file and deletes itself.
3. Do not commit. Hand back to the agent, which commits Phase A as one commit (L68).

| file | → | before | after | edits |
| ---- | - | ------ | ----- | ----- |
`;
for (const f of data) md += `| \`${f.path}\` | ${f.new_path ? `\`${f.new_path}\`` : "—"} | \`${f.before_sha.slice(0, 12)}…\` | \`${f.after_sha.slice(0, 12)}…\` | ${f.edits.length} |\n`;
md += "\nFull hashes (sha256):\n\n```text\n";
for (const f of data) md += `${f.path}\n  before ${f.before_sha}\n  after  ${f.after_sha}\n`;
md += "```\n";
for (const f of data) {
  md += `\n## \`${f.path}\`${f.new_path ? ` → \`${f.new_path}\`` : ""}\n`;
  f.edits.forEach((e, i) => {
    md += `\n### ${f.path} — edit ${i + 1} (near line ${e.line})\n\nOld text:\n\n${fence(e.old)}text\n${e.old}\n${fence(e.old)}\n\nNew text:\n\n${fence(e.new)}text\n${e.new}\n${fence(e.new)}\n`;
  });
}
fs.writeFileSync(path.join(OUT, "HUMAN-PATCH.md"), md);
console.log(data.map((f) => `${f.path}: ${f.edits.length} edits`).join("\n"));
