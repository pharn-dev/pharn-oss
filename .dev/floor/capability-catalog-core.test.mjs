// --- fixtures for the README `## Current state` block -------------------------------------------

const MARK_BEGIN =
  "<!-- CURRENT-STATE:BEGIN — GENERATED by .dev/floor/gen-capability-catalog.mjs. DO NOT EDIT BETWEEN MARKERS. Regenerate: npm run docs:generate -->";
const MARK_END = "<!-- CURRENT-STATE:END -->";
const readmeWith = (inner) => `# Fixture\n\n## Current state\n\nIntro prose.\n\n${MARK_BEGIN}\n${inner}${MARK_END}\n\nTail prose.\n`;

/** Create the four directories renderReadmeCurrentState enumerates. */
function surface(root, opts = {}) {
  const {
    contracts = ["finding-shape.md", "eval-format.md"],
    commands = ["pharn-spec.md", "pharn-plan.md", "pharn-dev-plan.md"],
    hooks = ["protect-trusted-paths.cjs", "protect-trusted-paths.test.cjs"],
    floor = ["validate.mjs", "check-spec.mjs", "validate.test.mjs"],
  } = opts;
  const put = (rel, names, body) => {
    mkdirSync(join(root, rel), { recursive: true });
    for (const n of names) writeFileSync(join(root, rel, n), body);
  };
  // No `role:` frontmatter anywhere here, so none of these is ever counted as a capability.
  put("pharn/pharn-contracts", contracts, "# a contract\n");
  put(".claude/commands", commands, "# a command\n");
  put(".claude/hooks", hooks, "// a hook\n");
  put("pharn/floor", floor, "// a checker\n");
  writeFileSync(join(root, README_PATH), readmeWith("\n\n"));
}

// Write a capability at <root>/<dirRel>/<base>.md with the given frontmatter map + body.
function cap(root, dirRel, base, fm, body) {
  const dir = join(root, dirRel);
  mkdirSync(dir, { recursive: true });
  const fmLines = Object.entries(fm).map(([k, v]) => `${k}: ${Array.isArray(v) ? `[${v.map((x) => `"${x}"`).join(", ")}]` : v}`);
  writeFileSync(join(dir, `${base}.md`), `---\n${fmLines.join("\n")}\n---\n\n${body}\n`);
}

