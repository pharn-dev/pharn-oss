  assert.throws(() => extractCurrentState("# no markers here\n"), /no <!-- CURRENT-STATE:BEGIN/);
  assert.throws(() => extractCurrentState(`${MARK_BEGIN}\n\nbody\n`), /no <!-- CURRENT-STATE:END/);
  assert.throws(() => extractCurrentState(`${MARK_BEGIN}\n${MARK_BEGIN}\n${MARK_END}\n`), /2 BEGIN markers found/);
  assert.throws(() => extractCurrentState(`${MARK_BEGIN}\n${MARK_END}\n${MARK_END}\n`), /2 END markers found/);
