test("splice: round-trips, keeps one blank line each side, preserves prose, and is idempotent", () => {
  const root = makeRepo();
  try {
    surface(root);
    const block = renderReadmeCurrentState(root);
    const once = spliceCurrentState(readmeWith("\n\n"), block);

    assert.equal(extractCurrentState(once).region, block, "what was spliced in is what comes back out");
    assert.match(once, /Intro prose\.\n\n<!-- CURRENT-STATE:BEGIN/);
    assert.match(once, /CURRENT-STATE:END -->\n\nTail prose\./);
    assert.match(once, /^# Fixture\n/); // untouched hand prose survives
    assert.equal(spliceCurrentState(once, block), once, "splicing an already-current README is a no-op");

    // Ragged whitespace around the markers is normalised to exactly one blank line, so the generator
    // converges in one pass instead of drifting forever.
    const ragged = `# F\n\nIntro.\n\n\n\n${MARK_BEGIN}\n\nstale\n\n${MARK_END}\n\n\n\nTail.\n`;
    const fixed = spliceCurrentState(ragged, block);
    assert.equal(fixed, `# F\n\nIntro.\n\n${block}\n\nTail.\n`);
    assert.equal(spliceCurrentState(fixed, block), fixed);

    // A region at end-of-file still ends the file with exactly one newline.
    assert.equal(spliceCurrentState(`# F\n\n${MARK_BEGIN}\n${MARK_END}\n`, block), `# F\n\n${block}\n`);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

